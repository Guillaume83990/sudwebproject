    /* ─── MOTEUR ───────────────────────────────────── */
    var KEY = 'swp_lang';
    /* Forcer FR par défaut — l'anglais n'est disponible qu'au clic explicite */
    var stored = localStorage.getItem(KEY);
    var lang = (stored === 'en') ? 'en' : 'fr';
    if (!stored) localStorage.setItem(KEY, 'fr');

    function t(key) {
        return (T[lang] && T[lang][key]) || (T.fr[key]) || key;
    }

    function apply() {
        document.querySelectorAll('[data-i18n]').forEach(function (el) {
            var key = el.getAttribute('data-i18n');
            var val = t(key);
            if (!val) return;

            /* ── CAS SPÉCIAL : span.split-reveal ──────────────
               Mise à jour directe du texte traduit, sans scramble.
               L'animation clip-path reveal reste intacte.        */
            if (el.classList && el.classList.contains('split-reveal')) {
                if (val.indexOf('<') !== -1) {
                    el.innerHTML = val;
                } else {
                    el.textContent = val;
                }
                return;
            }

            /* ── CAS NORMAL ────────────────────────────────── */
            /* Remplacer {year} par l'année courante */
            if (val.indexOf('{year}') !== -1) {
                val = val.replace('{year}', new Date().getFullYear());
            }

            if (val.indexOf('<') !== -1) {
                el.innerHTML = val;
            } else if (el.tagName === 'H1' || el.tagName === 'H2' || el.tagName === 'H3') {
                el.innerHTML = val.replace(/\n/g, '<br>');
            } else {
                el.textContent = val;
            }
        });

        /* ── PLACEHOLDERS (data-i18n-placeholder) ── */
        document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
            var key = el.getAttribute('data-i18n-placeholder');
            var val = t(key);
            if (val) el.setAttribute('placeholder', val);
        });

        /* ── OPTGROUP LABELS (data-i18n-label) ── */
        document.querySelectorAll('[data-i18n-label]').forEach(function (el) {
            var key = el.getAttribute('data-i18n-label');
            var val = t(key);
            if (val) el.setAttribute('label', val);
        });

        document.documentElement.lang = lang;
    }

    function setLang(l) {
        if (!T[l]) return;
        lang = l;
        localStorage.setItem(KEY, l);
        apply();
        updateBtns();
        /* Mettre à jour le texte du morph button au repos */
        if (window._swpUpdateMorph) window._swpUpdateMorph();
    }

    function updateBtns() {
        document.querySelectorAll('.lang-btn[data-lang]').forEach(function (btn) {
            var active = btn.getAttribute('data-lang') === lang;
            btn.classList.toggle('active', active);
            btn.setAttribute('aria-pressed', active ? 'true' : 'false');
        });
    }

    function init() {
        document.querySelectorAll('.lang-btn[data-lang]').forEach(function (btn) {
            btn.addEventListener('click', function () {
                setLang(this.getAttribute('data-lang'));
            });
        });
        apply();
        updateBtns();
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', init);
    } else {
        init();
    }

    /* API publique */
    window.SWPi18n = { setLang: setLang, t: t, getLang: function () { return lang; } };

